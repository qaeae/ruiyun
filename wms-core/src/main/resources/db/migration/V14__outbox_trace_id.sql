-- 发件箱记录 traceId（P4 全链路追踪）
--
-- 为什么必须把 traceId 落库而不是只放在内存/MDC：
--   事件的**投递时机与产生时机不同**——审批请求的 traceId 在请求线程的 MDC 里，
--   而补投是由定时任务线程执行的（MDC 里没有它）。不落库的话，
--   "这笔审批最终执行了没有、执行时属于哪次请求"就无法关联，
--   排查时只能在两份日志里靠时间戳猜。
--
--   落库后：消费与投递日志都能打出**原始请求的 traceId**，
--   一条链路从网关 → 服务 → 发件箱 → MQ → 消费者 全程可串起来。
-- ==========================================================================================
ALTER TABLE pf_outbox
    ADD COLUMN trace_id VARCHAR(64) NULL COMMENT '产生该事件的请求 traceId（全链路追踪用，可空）' AFTER routing_key,
    ADD KEY idx_trace_id (trace_id);
