-- 审批"一事一单"的最后防线补到 biz_no 上（2026-10-14 联调抓出的真实缺陷）
--
-- 问题（联调第二次运行暴露）：
--   1) 结算下发时 `bizId` 传了占位值 0，所有批次共用一个"业务对象" → **第二次下付款永远被拒**（80003）；
--   2) 库存调整时 `bizId` 传 null，而 `selectByBiz` 对 null 直接返回 null → **完全没有防重**
--      （MySQL 唯一键对多个 NULL 视为互不相同）→ 同一调整可提交两张审批单，**都通过即重复扣减**。
--
-- 因此把业务对象标识的唯一性补到 `biz_no`（两个调用方都必然有业务单号）：
--   库存调整用 `ADJUST-<skuId>-<locationId>`，结算下发用批次号 `stbNo`。
--
-- 为什么必须落在数据库而不是只靠应用层判断：
--   应用层"先查再插"在并发下会同时通过检查，双双插入（两张待复核单都没被拒），
--   而两张单可以分别被通过 → 真正动钱的动作被执行两次。唯一键是**最后防线**。
ALTER TABLE au_approval
  ADD UNIQUE KEY uk_approval_biz_no (tenant_id, biz_type, biz_no);
